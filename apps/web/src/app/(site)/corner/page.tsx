function MessageCard({ note }: { note: Notification }) {
  return (
    <article className={styles.message} data-kind={note.kind}>
      <header className={styles.messageHead}>
        <span className={styles.to}>
          To: {note.to.name} <span className={styles.email}>&lt;{note.to.email}&gt;</span>
        </span>
        <span className={styles.kind}>
          {note.kind === 'inactivity-alert' ? 'Alert' : `Level ${note.to.level}`}
        </span>
      </header>
      <p className={styles.subject}>{note.subject}</p>
      <div className={styles.blocks}>
        {note.body.map((block, i) => (
          <Block key={i} block={block} />
        ))}
      </div>
    </article>
  );
}

function Block({ block }: { block: NotificationBlock }) {
  switch (block.type) {
    case 'paragraph':
      return <p className={styles.para}>{block.text}</p>;
    case 'stat':
      return (
        <p className={styles.stat}>
          <span>{block.label}</span>
          <strong>{block.value}</strong>
        </p>
      );
    case 'list':
      return (
        <div className={styles.list}>
          <p className={styles.listTitle}>{block.title}</p>
          <ul>
            {block.items.map((item, i) => (
              <li key={i}>{item}</li>
            ))}
          </ul>
        </div>
      );
    case 'questions':
      return (
        <div className={styles.questions}>
          <p className={styles.listTitle}>{block.title}</p>
          <ol>
            {block.questions.map((q, i) => (
              <li key={i}>
                <span className={styles.question}>{q.question}</span>
                <span className={styles.rationale}>{q.rationale}</span>
              </li>
            ))}
          </ol>
        </div>
      );
    case 'note':
      return <p className={styles.noteBlock}>{block.text}</p>;
  }
}

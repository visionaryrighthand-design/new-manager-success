/**
 * Renders real output from `@nms/core` rather than a static mockup.
 *
 * This page is the sales conversation with an HR buyer, and the fastest way to
 * lose that conversation is to show a designed screenshot that the shipped
 * product does not match. Everything below is produced by the same functions
 * that will send the actual emails.
 */

const DEMO_ENROLLMENT: Enrollment = {
  id: 'demo',
  entry: 'other-individual',
  student: { name: 'Dana Reyes', email: 'dana@example.com' },
  registeredBy: { name: 'Sam Okafor', email: 'sam@example.com' },
  startedAt: new Date('2026-07-27T09:00:00Z'),
  contacts: [
    { id: 'c1', name: 'Lee Park', email: 'lee@example.com', role: 'boss', level: 1 },
    { id: 'c2', name: 'Jo Silva', email: 'jo@example.com', role: 'hr', level: 2 },
    { id: 'c3', name: 'Sam Okafor', email: 'sam@example.com', role: 'registrant', level: 3 },
  ],
};

function buildDemo() {
  const week = { start: new Date('2026-08-10T00:00:00Z'), end: new Date('2026-08-17T00:00:00Z') };
  let progress = emptyProgress('demo', DEMO_ENROLLMENT.startedAt);

  for (const [i, repId] of ['m1-r1', 'm1-r2', 'm1-r3'].entries()) {
    const at = new Date(`2026-08-1${1 + i}T10:00:00Z`);
    progress = applyActivity(progress, {
      id: `open-${repId}`,
      enrollmentId: 'demo',
      type: 'rep-opened',
      repId,
      at,
    });
    progress = applyActivity(progress, {
      id: `done-${repId}`,
      enrollmentId: 'demo',
      type: 'rep-completed',
      repId,
      at,
    });
  }

  // A perfect run on 1.1, a miss on 1.3 — a digest that is all green reads as
  // marketing. Buyers trust a report that can show a bad week.
  progress = recordQuizAttempt(
    progress,
    'm1-r1',
    module01.reps[0]!.quiz.map((q) => ({
      questionId: q.id,
      optionId: q.options.find((o) => o.correct)!.id,
    })),
    new Date('2026-08-11T10:20:00Z'),
  ).progress;

  progress = recordQuizAttempt(
    progress,
    'm1-r3',
    module01.reps[2]!.quiz.map((q, i) => ({
      questionId: q.id,
      optionId: (i === 0 ? q.options.find((o) => !o.correct) : q.options.find((o) => o.correct))!.id,
    })),
    new Date('2026-08-13T10:20:00Z'),
  ).progress;

  const level1 = sectionCompleteNotifications(DEMO_ENROLLMENT, 'm1-r3');

  const digests = weeklyDigestNotifications({
    enrollment: DEMO_ENROLLMENT,
    progress,
    weekStart: week.start,
    weekEnd: week.end,
    fieldNoteAnswers: [
      {
        repId: 'm1-r2',
        fieldNoteId: 'm1-r2-fn1',
        topic: 'The doer trap',
        text: 'I am still building the weekly client report myself. Priya could do it but the last version she sent had errors and I did not want to have that conversation.',
        savedAt: new Date('2026-08-12T11:00:00Z'),
      },
      {
        repId: 'm1-r3',
        fieldNoteId: 'm1-r3-fn1',
        topic: 'Relationship reset',
        text: 'Marcus and I used to complain about management together. Now I am management and he has basically stopped talking to me.',
        savedAt: new Date('2026-08-13T11:00:00Z'),
      },
    ],
  });

  const inactivity = inactivityNotifications({
    enrollment: DEMO_ENROLLMENT,
    lastActivityAt: new Date('2026-08-13T10:00:00Z'),
    now: new Date('2026-08-24T09:00:00Z'),
  });

  return {
    level1: level1[0]!,
    level2: digests.find((d) => d.to.level === 2)!,
    level3: digests.find((d) => d.to.level === 3)!,
    inactivity: inactivity.notifications[0]!,
    inactivityState: inactivity.state,
  };
}

